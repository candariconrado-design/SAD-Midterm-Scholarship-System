-- SAD Midterm Scholarship System
-- Initial schema and Row Level Security policies.
-- Run once in a NEW Supabase project SQL Editor. Do not run against a database
-- containing data you need to keep without reviewing the statements first.

create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  full_name text,
  role text not null default 'scholar' check (role in ('scholar','staff','admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.scholarship_programs (
  id uuid primary key default gen_random_uuid(),
  program_name text not null unique,
  required_gwa numeric(3,2) not null,
  max_gwa numeric(3,2) not null,
  min_units integer not null check (min_units >= 0),
  max_failed integer not null default 0 check (max_failed >= 0),
  max_incomplete integer not null default 0 check (max_incomplete >= 0),
  max_dropped integer not null default 0 check (max_dropped >= 0),
  deadline timestamptz not null default '2026-11-06 17:00:00+08',
  active boolean not null default true,
  created_at timestamptz not null default now(),
  check (required_gwa between 1 and 5),
  check (max_gwa between 1 and 5)
);

create table if not exists public.scholars (
  id uuid primary key default gen_random_uuid(),
  user_id uuid unique references auth.users(id) on delete set null,
  student_id text not null unique,
  full_name text not null,
  degree_program text not null,
  year_level text,
  scholarship_id uuid not null references public.scholarship_programs(id),
  status text not null default 'Active' check (status in ('Active','Inactive','Graduated')),
  created_by uuid references auth.users(id) on delete set null,
  created_at timestamptz not null default now()
);

create table if not exists public.grade_submissions (
  id uuid primary key default gen_random_uuid(),
  scholar_id uuid not null references public.scholars(id) on delete cascade,
  academic_year text not null,
  semester integer not null check (semester between 1 and 3),
  gwa numeric(3,2) not null check (gwa between 1 and 5),
  units_enrolled integer not null check (units_enrolled >= 0),
  failed_subjects integer not null default 0 check (failed_subjects >= 0),
  incomplete_subjects integer not null default 0 check (incomplete_subjects >= 0),
  dropped_subjects integer not null default 0 check (dropped_subjects >= 0),
  evidence_reference text not null,
  submitted_at timestamptz not null default now(),
  submission_status text not null default 'Pending'
    check (submission_status in ('Pending','Verified','Returned')),
  verification_reason text,
  verified_by uuid references auth.users(id) on delete set null,
  verified_at timestamptz,
  compliance_status text not null default 'Pending'
    check (compliance_status in ('Pending','Compliant','With Deficiency')),
  deficiency_reasons text[] not null default array[]::text[],
  evaluated_by uuid references auth.users(id) on delete set null,
  evaluated_at timestamptz,
  created_at timestamptz not null default now(),
  unique (scholar_id, academic_year, semester)
);

create table if not exists public.renewal_decisions (
  id uuid primary key default gen_random_uuid(),
  submission_id uuid not null unique references public.grade_submissions(id) on delete cascade,
  decision text not null check (decision in ('Approved','Held')),
  reason text,
  decided_by uuid references auth.users(id) on delete set null,
  decided_at timestamptz not null default now()
);

create table if not exists public.audit_logs (
  id bigint generated by default as identity primary key,
  actor_id uuid references auth.users(id) on delete set null,
  action text not null,
  entity_type text not null,
  entity_id uuid,
  details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists idx_scholars_user_id on public.scholars(user_id);
create index if not exists idx_grade_submissions_scholar on public.grade_submissions(scholar_id);
create index if not exists idx_grade_submissions_status on public.grade_submissions(submission_status, compliance_status);
create index if not exists idx_audit_logs_created_at on public.audit_logs(created_at desc);

-- New Auth accounts receive a Scholar profile. Staff must be promoted by a trusted admin.
create or replace function public.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, full_name, role)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'full_name', split_part(coalesce(new.email,''),'@',1)),
    'scholar'
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created_profile on auth.users;
create trigger on_auth_user_created_profile
after insert on auth.users
for each row execute procedure public.handle_new_auth_user();

create or replace function public.is_staff()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.profiles p
    where p.id = auth.uid() and p.role in ('staff','admin')
  );
$$;

alter table public.profiles enable row level security;
alter table public.scholarship_programs enable row level security;
alter table public.scholars enable row level security;
alter table public.grade_submissions enable row level security;
alter table public.renewal_decisions enable row level security;
alter table public.audit_logs enable row level security;

drop policy if exists profiles_select_own_or_staff on public.profiles;
create policy profiles_select_own_or_staff on public.profiles
for select to authenticated
using (id = auth.uid() or public.is_staff());

drop policy if exists programs_read_authenticated on public.scholarship_programs;
create policy programs_read_authenticated on public.scholarship_programs
for select to authenticated using (active = true or public.is_staff());

drop policy if exists programs_staff_manage on public.scholarship_programs;
create policy programs_staff_manage on public.scholarship_programs
for all to authenticated using (public.is_staff()) with check (public.is_staff());

drop policy if exists scholars_staff_manage on public.scholars;
create policy scholars_staff_manage on public.scholars
for all to authenticated using (public.is_staff()) with check (public.is_staff());

drop policy if exists scholars_read_own_or_staff on public.scholars;
create policy scholars_read_own_or_staff on public.scholars
for select to authenticated using (user_id = auth.uid() or public.is_staff());

drop policy if exists submissions_read_own_or_staff on public.grade_submissions;
create policy submissions_read_own_or_staff on public.grade_submissions
for select to authenticated
using (
  public.is_staff() or exists (
    select 1 from public.scholars sc
    where sc.id = grade_submissions.scholar_id and sc.user_id = auth.uid()
  )
);

drop policy if exists submissions_insert_own on public.grade_submissions;
create policy submissions_insert_own on public.grade_submissions
for insert to authenticated
with check (
  submission_status = 'Pending'
  and compliance_status = 'Pending'
  and exists (
    select 1 from public.scholars sc
    where sc.id = grade_submissions.scholar_id and sc.user_id = auth.uid()
  )
);

drop policy if exists submissions_correct_returned_own on public.grade_submissions;
create policy submissions_correct_returned_own on public.grade_submissions
for update to authenticated
using (
  submission_status = 'Returned'
  and exists (
    select 1 from public.scholars sc
    where sc.id = grade_submissions.scholar_id and sc.user_id = auth.uid()
  )
)
with check (
  submission_status = 'Pending'
  and compliance_status = 'Pending'
  and exists (
    select 1 from public.scholars sc
    where sc.id = grade_submissions.scholar_id and sc.user_id = auth.uid()
  )
);

drop policy if exists renewal_read_own_or_staff on public.renewal_decisions;
create policy renewal_read_own_or_staff on public.renewal_decisions
for select to authenticated
using (
  public.is_staff() or exists (
    select 1
    from public.grade_submissions gs
    join public.scholars sc on sc.id = gs.scholar_id
    where gs.id = renewal_decisions.submission_id and sc.user_id = auth.uid()
  )
);

drop policy if exists audit_read_staff on public.audit_logs;
create policy audit_read_staff on public.audit_logs
for select to authenticated using (public.is_staff());

drop policy if exists audit_insert_own_actor on public.audit_logs;
create policy audit_insert_own_actor on public.audit_logs
for insert to authenticated with check (actor_id = auth.uid());

grant usage on schema public to authenticated;
grant select on public.profiles to authenticated;
grant select, insert, update on public.grade_submissions to authenticated;
grant select on public.renewal_decisions to authenticated;
grant select, insert on public.audit_logs to authenticated;
grant select on public.scholarship_programs to authenticated;
grant select, insert, update, delete on public.scholarship_programs to authenticated;
grant select, insert, update, delete on public.scholars to authenticated;
grant execute on function public.is_staff() to authenticated;

